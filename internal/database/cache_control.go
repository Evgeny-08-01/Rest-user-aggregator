// ============================================================
// ПАКЕТ: database
// ФАЙЛ: cache_control.go
// НАЗНАЧЕНИЕ: методы для работы с версией кеша пользователя в БД
// ============================================================
//
// ЗАЧЕМ НУЖНА ВЕРСИЯ:
//   - Каждое изменение данных пользователя (Create/Update/Delete подписки)
//     увеличивает версию на 1.
//   - Ключ кеша в Redis включает номер версии.
//   - Когда версия меняется — старый ключ перестаёт читаться,
//     потому что новый ключ строится с новой версией.
//   - Это даёт мгновенную инвалидацию кеша без необходимости
//     искать и удалять старые ключи.
//
// ПОЧЕМУ ВЕРСИЯ ХРАНИТСЯ В БД, А НЕ В REDIS:
//   - БД — единственный источник истины.
//   - Redis может потерять данные при сбое.
//   - Если Redis упадёт и восстановится — версия из БД всё равно
//     будет правильной, и старый кеш не будет использован.
//   - Если БД недоступна — мы вообще не используем кеш,
//     идём напрямую в БД.
//
// СТРУКТУРА ТАБЛИЦЫ:
//   CREATE TABLE cache_control_user (
//       user_id UUID PRIMARY KEY,
//       version INT NOT NULL DEFAULT 1
//   );
//
//   - Одна строка на пользователя.
//   - При первом обращении создаётся с version = 1.
//   - При каждом изменении данных — version увеличивается на 1.
// ============================================================

package database

import (
	"context"

	"Rest-user-agregator/pkg/logger"
)

// ============================================================
// 1. ПОЛУЧЕНИЕ ВЕРСИИ ПОЛЬЗОВАТЕЛЯ
// ============================================================

// GetCacheUserVersion — возвращает текущую версию кеша для пользователя.
//
// ПАРАМЕТРЫ:
//   - ctx: контекст для управления временем жизни запроса
//   - userID: идентификатор пользователя (UUID)
//
// ВОЗВРАЩАЕТ:
//   - int: текущая версия (число, начиная с 1)
//   - error: ошибка, если не удалось прочитать или создать запись
//
// ЛОГИКА РАБОТЫ:
//
//	Задача: получить число (версию) для конкретного пользователя.
//	Проблема: у нового пользователя в таблице ещё нет записи.
//	Решение:
//	  1. Пытаемся вставить запись (user_id, version=1).
//	     - Если пользователь уже есть в таблице — ON CONFLICT ничего не делает.
//	     - Если пользователя нет — создаём строку с version = 1.
//	  2. Читаем версию из таблицы.
//	     - После шага 1 запись ТОЧНО существует.
//	     - Забираем число version и возвращаем его.
//
//	Простыми словами: "Дай мне версию пользователя.
//	Если у него ещё нет записи — создай со значением 1 и верни."
//
// ПОЧЕМУ INSERT ПЕРЕД SELECT:
//   - Гарантирует, что строка для пользователя всегда существует.
//   - Не нужно делать отдельный запрос на проверку существования.
//   - ON CONFLICT — атомарная операция, безопасна при конкурентных запросах.
//
// ПРИМЕР:
//   - Первый запрос для пользователя "123" → INSERT + SELECT → version = 1
//   - Второй запрос (без изменений) → SELECT → version = 1
//   - После обновления подписки → SELECT → version = 2 (инкремент)
//   - После удаления подписки → SELECT → version = 3 (инкремент)
func (r *PostgresRepo) GetCacheUserVersion(ctx context.Context, userID string) (int, error) {
	var version int
	// 1. Вставляем запись, если её нет
	//    ON CONFLICT (user_id) — если user_id уже существует, ничего не делаем.
	//    Это безопасно при параллельных запросах.
	query := `INSERT INTO cache_control_user (user_id, version) 
	          VALUES ($1, 1) 
	          ON CONFLICT (user_id) DO NOTHING`

	_, err := r.db.ExecContext(ctx, query, userID)
	if err != nil {
		logger.Error("GetCacheUserVersion: failed to insert cache_control_user for %s: %v", userID, err)
		logger.Debug("из GetCacheUserVersion сразу после вызова userID %s:", userID) // удалить!
		return 0, err
	}

	// 2. Читаем текущую версию
	//    После шага 1 запись гарантированно существует.
	query = `SELECT version FROM cache_control_user WHERE user_id = $1`
	err = r.db.QueryRowContext(ctx, query, userID).Scan(&version)
	if err != nil {
		logger.Debug("GetCacheUserVersion: failed to get version for user %s: %v", userID, err)
		return 0, err
	}

	logger.Debug("GetCacheUserVersion: user %s version = %d", userID, version)
	return version, nil
}

// ============================================================
// 2. ИНКРЕМЕНТ ВЕРСИИ ПОЛЬЗОВАТЕЛЯ
// ============================================================

// IncrementCacheUserVersion — увеличивает версию кеша для пользователя на 1.
//
// ПАРАМЕТРЫ:
//   - ctx: контекст
//   - userID: идентификатор пользователя
//
// ВОЗВРАЩАЕТ:
//   - error: ошибка, если не удалось обновить запись
//
// ЛОГИКА РАБОТЫ:
//
//	Задача: увеличить версию пользователя на 1 при изменении его данных.
//	Проблема: у нового пользователя может не быть записи.
//	Решение:
//	  1. Пытаемся обновить существующую запись: version = version + 1.
//	  2. Если записи нет — создаём новую со значением 1.
//
//	Простыми словами: "Увеличь версию пользователя на 1.
//	Если записи нет — создай со значением 1."
//
// КОГДА ВЫЗЫВАТЬ:
//   - После успешного создания подписки (CreateSubscription)
//   - После успешного обновления подписки (UpdateSubscription)
//   - После успешного удаления подписки (DeleteSubscription)
//
// ПОЧЕМУ ON CONFLICT:
//   - Гарантирует, что строка всегда существует.
//   - Если пользователь новый — создаём с version = 1.
//   - Если уже есть — увеличиваем на 1.
//   - Атомарная операция, безопасна при параллельных запросах.
//
// ПОСЛЕДСТВИЯ ИНКРЕМЕНТА:
//   - Все кеши этого пользователя становятся невалидными.
//   - Новые ключи будут строиться с увеличенной версией.
//   - Старые ключи в Redis игнорируются.
func (r *PostgresRepo) IncrementCacheUserVersion(ctx context.Context, userID string) error {
	query := `INSERT INTO cache_control_user (user_id, version) 
	          VALUES ($1, 1) 
	          ON CONFLICT (user_id) DO UPDATE SET version = cache_control_user.version + 1`

	_, err := r.db.ExecContext(ctx, query, userID)
	if err != nil {
		logger.Error("IncrementCacheUserVersion: failed to increment version for user %s: %v", userID, err)
		return err
	}

	logger.Debug("IncrementCacheUserVersion: incremented version for user %s", userID)
	return nil
}
